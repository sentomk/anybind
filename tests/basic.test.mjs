import { test } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const addonPath = fileURLToPath(
  new URL("../build/tests/test_basic.node", import.meta.url),
);
const stubgen = fileURLToPath(
  new URL("../bin/anybind-stubgen.mjs", import.meta.url),
);
const m = require(addonPath);

test("converts arguments and return values", () => {
  assert.equal(m.add(2, 3), 5);
  assert.equal(m.scale(1.5, 2), 3);
  assert.equal(m.greet("anybind"), "hello, anybind");
  assert.equal(m.negate(true), false);
  assert.equal(m.twice64(2 ** 40), 2 ** 41);
  assert.equal(m.noop(), undefined);
});

test("lambdas keep their captured state", () => {
  assert.equal(m.next(), 1);
  assert.equal(m.next(), 2);
});

test("rejects bad arguments with TypeError", () => {
  assert.throws(() => m.add("1", 2), {
    name: "TypeError",
    message: /argument 1: expected number/,
  });
  assert.throws(() => m.add(1, 1.5), {
    name: "TypeError",
    message: /argument 2: expected an integer/,
  });
  assert.throws(() => m.add(2 ** 31, 0), TypeError);
  assert.throws(() => m.add(Number.NaN, 0), TypeError);
  assert.throws(() => m.add(1), {
    name: "TypeError",
    message: /expected 2 argument\(s\), got 1/,
  });
  assert.throws(() => m.greet(42), {
    name: "TypeError",
    message: /expected string/,
  });
});

test("translates C++ exceptions", () => {
  assert.throws(() => m.fail(), { name: "Error", message: "boom" });
  assert.throws(() => m.rejectArg(1), {
    name: "TypeError",
    message: "custom type error",
  });
});

test("records TypeScript signatures without polluting exports", () => {
  assert.ok(!Object.keys(m).includes("__anybind_dts__"));
  assert.match(
    m.__anybind_dts__,
    /export function add\(arg0: number, arg1: number\): number;/,
  );
  assert.match(
    m.__anybind_dts__,
    /export function greet\(arg0: string\): string;/,
  );
  assert.match(m.__anybind_dts__, /export function noop\(\): void;/);
});

test("anybind-stubgen prints the declarations", () => {
  const r = spawnSync(process.execPath, [stubgen, addonPath], {
    encoding: "utf8",
  });
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /^\/\/ Generated by anybind-stubgen/);
  assert.match(r.stdout, /export function negate\(arg0: boolean\): boolean;/);
});

test("supports named arguments and default values", () => {
  assert.equal(m.power(3), 9);
  assert.equal(m.power(3, undefined), 9);
  assert.equal(m.power(2, 10), 1024);

  assert.equal(m.welcome(), "hello, world");
  assert.equal(m.welcome("anybind"), "hello, anybind");
  assert.equal(m.welcome(undefined, "hi"), "hi, world");

  // Non-trailing default: prefix can be undefined, id is required, suffix is optional.
  assert.equal(m.formatTag(undefined, 7), "item-7");
  assert.equal(m.formatTag("v", 2, "-beta"), "v2-beta");
});

test("includes parameter names and arity ranges in TypeError messages", () => {
  assert.throws(() => m.power(), {
    name: "TypeError",
    message: /expected 1 to 2 argument\(s\), got 0/,
  });
  assert.throws(() => m.power(1, 2, 3), {
    name: "TypeError",
    message: /expected 1 to 2 argument\(s\), got 3/,
  });
  assert.throws(() => m.power(2, "bad"), {
    name: "TypeError",
    message: /argument 2 \(exp\): expected number/,
  });
  assert.throws(() => m.formatTag(undefined, undefined), {
    name: "TypeError",
    message: /argument 2 \(id\): expected number/,
  });
});

test("emits named and optional parameters in .d.ts", () => {
  assert.match(
    m.__anybind_dts__,
    /export function power\(base: number, exp\?: number\): number;/,
  );
  assert.match(
    m.__anybind_dts__,
    /export function welcome\(who\?: string, prefix\?: string\): string;/,
  );
  assert.match(
    m.__anybind_dts__,
    /export function formatTag\(prefix: string \| undefined, id: number, suffix\?: string\): string;/,
  );
});
