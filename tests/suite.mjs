function runStubgen(targetAddon) {
  if (typeof globalThis.Deno !== "undefined") {
    return spawnSync(
      process.execPath,
      ["run", "--allow-all", stubgen, targetAddon],
      { encoding: "utf8" },
    );
  }
  const env = process.versions?.electron
    ? { ...process.env, ELECTRON_RUN_AS_NODE: "1" }
    : process.env;
  return spawnSync(process.execPath, [stubgen, targetAddon], {
    encoding: "utf8",
    env,
  });
}

