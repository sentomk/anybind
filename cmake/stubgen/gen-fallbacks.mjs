// Generates stubs for the Node-API functions that recorder.cpp does not
// implement, so that bindings calling them still link into the stub
// generator. Each stub fails with "not supported during stub generation".
//
//   node gen-fallbacks.mjs <recorder.cpp> <output.cpp> <anybind root>

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const [recorderPath, outPath, anybindRoot] = process.argv.slice(2);
if (!recorderPath || !outPath || !anybindRoot) {
  console.error(
    "usage: gen-fallbacks.mjs <recorder.cpp> <output.cpp> <anybind root>",
  );
  process.exit(2);
}

const require = createRequire(import.meta.url);
const symbols = require(
  require.resolve("node-api-headers/symbols", { paths: [anybindRoot] }),
);
const all = new Set();
for (const version of Object.values(symbols)) {
  for (const name of version.js_native_api_symbols) all.add(name);
  for (const name of version.node_api_symbols) all.add(name);
}

// recorder.cpp defines its functions as `... NAPI_CDECL napi_name(`.
const implemented = new Set(
  [
    ...readFileSync(recorderPath, "utf8").matchAll(
      /NAPI_CDECL\s+((?:napi|node_api)_\w+)\s*\(/g,
    ),
  ].map((m) => m[1]),
);

const missing = [...all].filter((name) => !implemented.has(name)).sort();
const lines = [
  "// Generated by anybind (cmake/stubgen/gen-fallbacks.mjs). Do not edit.",
  "//",
  "// Node-API functions the stub generator does not implement. They are",
  "// declared without parameters on purpose: this file does not include the",
  "// Node-API headers, and each stub only records which function was called.",
  'extern "C" int anybind_stubgen_unsupported(const char* name);',
  "",
  ...missing.map(
    (name) =>
      `extern "C" int ${name}() { return anybind_stubgen_unsupported("${name}"); }`,
  ),
  "",
];
const text = lines.join("\n");
let previous = "";
try {
  previous = readFileSync(outPath, "utf8");
} catch {}
if (previous !== text) writeFileSync(outPath, text);
